def without_demo_note(body):
    """各オブジェクトに重ねていた展示注記を、保存前に取り除く。"""
    for note in ("（架空の展示設定）", "これは展示用の架空設定である。", "架空の展示設定。", "架空の展示用。"):
        body = body.replace(note, "")
    return body


