/* Pythonの実DB履歴を入力に、ブラウザーの同期と復旧判断を検査する。 */
"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const M = require("../tools/graph_demo/static/model.js");
const {before, draft, after} = JSON.parse(fs.readFileSync(0, "utf8"));
assert.equal(M.transition(null, before).type, "LOAD");
assert.equal(M.transition(before, before).type, "SAME");
assert.equal(M.transition(before, draft).events.length, 0);
assert.equal(M.transition(draft, after).events.length, 1);
assert.equal(M.transition(before, after).events.length, 1);
assert.equal(M.transition(before, after, true).events.length, 0);
assert.equal(M.transition(before, after, true).type, "RECONNECTED");
assert.equal(M.transition(after, before).type, "RESET");
const other = structuredClone(after);
other.meta.database_id = "other";
assert.equal(M.transition(before, other).type, "RESET");
const branch = structuredClone(after);
branch.commits.find(c => c.graph_revision === before.meta.graph_revision).snapshot_id = "branch";
assert.equal(M.transition(before, branch).type, "RESET");
const sameRevisionBranch = structuredClone(before);
sameRevisionBranch.meta.snapshot_id = "branch";
sameRevisionBranch.commits.at(-1).snapshot_id = "branch";
assert.equal(M.transition(before, sameRevisionBranch).type, "RESET");
const gap = structuredClone(after);
gap.commits = gap.commits.filter(c => c.graph_revision !== draft.meta.graph_revision);
assert.equal(M.transition(before, gap).type, "RESET");
assert.throws(() => M.validate({meta:{}}));
for (const name of [undefined,"", "   "]) {
  const unnamed=structuredClone(after);unnamed.meta.project_name=name;
  assert.throws(()=>M.validate(unnamed));
}
const malformed = structuredClone(after);
delete malformed.nodes[0].created_at;
assert.throws(() => M.validate(malformed));
const malformedHistory = structuredClone(after);
malformedHistory.revisions[0].snapshot = {};
assert.throws(() => M.validate(malformedHistory));
const change = M.transition(draft, after).events[0].changes[0];
assert.equal(change.before.id, change.after.id);
assert.notEqual(change.before.revision_id, change.after.revision_id);
assert.equal(M.textDiff("通常ログ24時間", "通常ログ48時間").removed, "24");
assert.equal(M.textDiff("通常ログ24時間", "通常ログ48時間").added, "48");
assert.deepEqual(M.textDiff("😀24", "😀48"), {prefix:"😀", removed:"24", added:"48", suffix:""});
const normal = before.nodes.find(n => n.title === "通常ログの保持期間");
assert.equal(before.display_numbers[normal.id],after.display_numbers[normal.id]);
const normalNumber = M.displayNumber(before,normal.id);
assert.equal(M.matchesQuery(before,normal,[normalNumber.toLowerCase()]),true);
const otherAgreement = before.nodes.find(n=>n.kind === "agreement" && n.id !== normal.id);
assert.equal(M.matchesQuery(before,otherAgreement,[normalNumber.toLowerCase()]),false);
const invalidNumbers = structuredClone(after);
invalidNumbers.display_numbers[normal.id] = "A-01";
assert.throws(()=>M.validate(invalidNumbers));
const context = M.contexts(before, normal.id);
assert.ok(context.some(c => c.node.kind === "rationale" && c.relation.relation_kind === "supports"));
assert.ok(M.groups(before).at(-1).id === "");
console.log("実履歴からの同期・再送・分岐・復旧・原文差分: 合格");
